// Map into rich full products with unique IDs and related product IDs
export const PRODUCTS_DATABASE: Product[] = RAW_PRODUCTS.map((item, index) => {
  const id = `prod-${index + 1}`;
  return {
    id,
    sku: item.sku,
    name: item.name,
    category: item.category,
    price: item.price,
    salePrice: item.salePrice,
    netQuantity: item.netQuantity,
    stock: item.stock,
    rating: item.rating,
    reviewCount: item.reviewCount,
    isDemoReviewCount: true,
    description: item.description,
    keyFeatures: item.keyFeatures,
    ingredients: item.ingredients,
    usageInstructions: item.usageInstructions,
    precautions: item.precautions,
    variants: (item.variants || []).map((v, vIdx) => ({
      ...v,
      id: `v-${index + 1}-${vIdx + 1}`,
    })),
    image: item.image,
    secondaryImage: item.secondaryImage || item.image,
    isFeatured: item.isFeatured ?? false,
    isBestseller: item.isBestseller ?? false,
    isNewArrival: item.isNewArrival ?? false,
    searchKeywords: item.searchKeywords,
    relatedProductIds: [],
  };
});

// Link related products within same category
PRODUCTS_DATABASE.forEach((prod) => {
  const siblings = PRODUCTS_DATABASE.filter(
    (p) => p.category === prod.category && p.id !== prod.id
  );
  prod.relatedProductIds = siblings.slice(0, 4).map((p) => p.id);
});

